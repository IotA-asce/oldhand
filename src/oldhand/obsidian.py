"""Native, opt-in Obsidian links over the canonical Markdown archive."""

from __future__ import annotations

import hashlib
import json
import os
from pathlib import Path
import re
from urllib.parse import quote

from .records import GRAPH_END, GRAPH_START, graph_section_range
from .validation import validate_records
from .workspace import _atomic_write, collection_name


GENERATED = "<!-- oldhand:generated -->"
CONFIG = {"generator": "oldhand obsidian", "version": 1}


def _label(text: str) -> str:
    text = " ".join(text.splitlines())
    return re.sub(r"([\\\[\]`*_<>])", r"\\\1", text)


def _link(source: Path, target: Path, label: str) -> str:
    relative = Path(os.path.relpath(target, source.parent)).as_posix()
    return f"[{_label(label)}]({quote(relative, safe='/')})"


def _topic_path(root: Path, topic: str) -> Path:
    # The digest disambiguates case, punctuation, Unicode and truncated slugs;
    # raw topic names must never be interpreted as filesystem paths.
    slug = re.sub(r"[^a-z0-9]+", "-", topic.lower()).strip("-")[:40] or "topic"
    digest = hashlib.sha256(topic.encode("utf-8")).hexdigest()[:12]
    return root / "_topics" / f"{slug}-{digest}.md"


def _check_path(root: Path, path: Path) -> None:
    path.relative_to(root)
    for candidate in (path, *path.parents):
        if candidate == root:
            break
        if candidate.is_symlink():
            raise ValueError(f"refusing symlink in Obsidian path: {path}")
    if path.exists() and not path.is_file():
        raise ValueError(f"Obsidian target is not a regular file: {path}")


def _generated_note(path: Path, allow_legacy_home: bool = False) -> bool:
    text = path.read_text(encoding="utf-8")
    return text.startswith(GENERATED + "\n") or (
        allow_legacy_home and text.startswith("# Oldhand\n") and text.endswith(
            "Generated by `oldhand obsidian`. Edits here are overwritten.\n"
            "Canonical records live under each collection's `memory/`."))


def _record_text(text: str, lines: list[str]) -> str:
    newline = "\r\n" if "\r\n" in text else "\n"
    block = newline.join([GRAPH_START, "## Obsidian graph", "", *lines,
                          "", GRAPH_END, ""])
    owned = graph_section_range(text)
    if owned is not None:
        return text[:owned[0]] + block + text[owned[1]:]
    separator = "" if text.endswith(newline * 2) else newline if text.endswith(newline) else newline * 2
    return text + separator + block


def sync_graph(root: Path, enable: bool = False) -> tuple[int, int] | None:
    """Refresh owned links, returning record/topic counts, or None if disabled.

    Preflight all destinations before touching authored files. A failed write
    restores the previous bytes, including the previous enablement setting.
    No SQLite dependency: rebuild can call this before taking its snapshot.
    """
    root = root.resolve()
    config = root / "_topics" / ".oldhand.json"
    if not enable and not config.exists():
        return None
    _check_path(root, config)
    if config.exists() and json.loads(config.read_text(encoding="utf-8")) != CONFIG:
        raise ValueError(f"unrecognized Obsidian configuration: {config}")
    records, errors, _ = validate_records(root)
    if errors:
        raise ValueError("cannot synchronize an invalid archive: " + "; ".join(errors))

    by_id = {str(record["meta"]["id"]): record for record in records}
    topics: dict[str, list] = {}
    record_topics: dict[str, list[str]] = {}
    for rid, record in by_id.items():
        keys = sorted({topic.lower().strip().replace(" ", "-") for topic in record["topics"]})
        record_topics[rid] = keys
        for topic in keys:
            topics.setdefault(topic, []).append(record)
    # Match Oldhand's topic normalization. Case variants intentionally share
    # one semantic topic, rather than creating separate graph clusters.
    hubs = {topic: _topic_path(root, topic) for topic in topics}
    updates: dict[Path, bytes | None] = {}

    for rid, record in by_id.items():
        path = record["path"]
        lines = []
        if record_topics[rid]:
            lines.append("Topics: " + ", ".join(
                _link(path, hubs[topic], topic) for topic in record_topics[rid]))
        for kind, targets in sorted(record["relations"].items()):
            for target in sorted(set(targets)):
                other = by_id[target]
                lines.append(f"- **{kind}**: {_link(path, other['path'], other['title'])}")
        if not lines:
            lines.append("_No topics or outgoing relationships._")
        text = path.read_bytes().decode("utf-8")
        updates[path] = _record_text(text, lines).encode("utf-8")

    for topic, path in hubs.items():
        lines = [GENERATED, f"# {_label(topic)}", "",
                 "Generated by `oldhand obsidian`. Edits here are overwritten.", ""]
        for record in sorted(topics[topic], key=lambda r: (r["title"], str(r["path"]))):
            coll = collection_name(root, record["collection_root"])
            lines.append(f"- {_link(path, record['path'], record['title'])} "
                         f"({_label(coll)}; {record['meta']['status']})")
        updates[path] = ("\n".join(lines) + "\n").encode("utf-8")

    home = root / "HOME.md"
    lines = [GENERATED, "# Oldhand", "", f"{len(records)} record(s).", "",
             "Open **Graph view** to explore topics and relationships, or open a memory",
             "note and use **Open local graph**. These are the original editable records.",
             "", "## Topics", ""]
    for topic in sorted(topics):
        lines.append(f"- {_link(home, hubs[topic], topic)} ({len(topics[topic])})")
    lines += ["", "## Collections", ""]
    collections: dict[str, list] = {}
    for record in records:
        collections.setdefault(collection_name(root, record["collection_root"]), []).append(record)
    for coll, items in sorted(collections.items()):
        lines += [f"### {_label(coll)}", ""]
        for record in sorted(items, key=lambda r: (r["title"], str(r["path"]))):
            lines.append(f"- {_link(home, record['path'], record['title'])} "
                         f"({record['meta']['status']}; {record['meta']['importance']})")
        lines.append("")
    lines += ["Generated by `oldhand obsidian`. Edits here are overwritten.",
              "Oldhand refreshes this graph on rebuild. Authored record content remains canonical."]
    updates[home] = ("\n".join(lines) + "\n").encode("utf-8")

    for path in (root / "_topics").glob("*.md"):
        if path not in updates and not path.is_symlink() and _generated_note(path):
            updates[path] = None

    record_paths = {record["path"] for record in records}
    for path in updates:
        _check_path(root, path)
        if path.exists() and path not in record_paths:
            if not _generated_note(path, allow_legacy_home=path == home):
                raise ValueError(f"refusing to overwrite user note: {path}")
    updates[config] = (json.dumps(CONFIG, indent=2) + "\n").encode("utf-8")
    originals = {path: path.read_bytes() if path.exists() else None for path in updates}
    changed = []
    try:
        for path, data in updates.items():
            if data == originals[path]:
                continue
            path.parent.mkdir(parents=True, exist_ok=True)
            changed.append(path)
            if data is None:
                path.unlink()
            else:
                _atomic_write(path, data)
    except BaseException:
        for path in reversed(changed):
            original = originals[path]
            if original is None:
                path.unlink(missing_ok=True)
            else:
                _atomic_write(path, original)
        raise
    return len(records), len(topics)
